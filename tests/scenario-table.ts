#!/usr/bin/env bun
/**
 * The scenario table of `docs/TEST-SPEC-mutation-runner.md`, generated from the
 * test file.
 *
 * **It said "generated" in three places and there was no generator.** The table
 * was hand-written and `MU-59` compared it with the file, which is a check and
 * not a derivation — N9 of the 2026-10-14 fourth re-review, and the reviewer left
 * the choice between correcting the word and committing this. CLAUDE.md asks for
 * a computed answer where there is one, and there is one here: the scenarios
 * *are* the `test(` titles.
 *
 * What is generated is the scenario table only. The overview above it carries a
 * positive/negative label and a reason per row, which are judgements, and the
 * detail blocks are prose. Those stay written by a person; this removes the one
 * part that is transcription.
 *
 *   bun tests/scenario-table.ts --check    exit 1 if the file differs
 *   bun tests/scenario-table.ts --write    rewrite the table in place
 *
 * `MU-59` runs `--check`, so a hand edit to the table is still caught — the
 * guard does not go away, it just guards a derivation instead of a copy.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..');
export const SPEC = join(root, 'docs/TEST-SPEC-mutation-runner.md');
export const FILE = join(root, 'tests/integration/m-mu.runner.test.ts');

const BEGIN = '<!-- scenario-table: generated by tests/scenario-table.ts; do not edit by hand -->';
const END = '<!-- end scenario-table -->';

/**
 * Every test title in the file, in order.
 *
 * The regex matches the three quotings `m-tr.case-ids` matches — single, double
 * and backtick — and `it(` as well as `test(`, which is N5's cheap half: a title
 * written any of those ways was invisible to the old reader, and so was one
 * carrying no id at all.
 *
 * **`^[ \t]*`, not `^\s+`, and any chain of modifiers.** `\s` takes the newline,
 * so with the `m` flag the anchor reached over a blank line and not over `});`:
 * a top-level `test(` right after a closing brace was invisible, and so were
 * `.skip`, `.only`, `.each` and `.todo`. `m-tr.case-ids` corrected the same
 * anchor on 2026-10-12. Column 0 is safe here because the fixture specs sit in
 * template literals and those are blanked first. Finding 7 of the local review
 * of 2026-10-21; MU-59 holds it.
 */
export function titles(src: string): string[] {
  const out: string[] = [];
  const re = /^[ \t]*(?:test|it)(?:\.\w+(?:\([^)]*\))?)*\(\s*(['"`])((?:[^\\]|\\.)*?)\1/gm;
  let m: RegExpExecArray | null;
  const scanned = withoutTemplates(src);
  while ((m = re.exec(scanned)) !== null) out.push(m[2]);
  return out;
}

/**
 * The source with the **contents** of template literals blanked out.
 *
 * Without this, the fixture specs are read as tests of this file: they are
 * written as backtick strings holding real `test('…')` lines, and six of them —
 * `the policy is protected`, `in inner`, `in outer`, `quoted parents`, `an
 * unrelated survivor` — came back as unlabelled tests the first time this ran.
 * They are test **data**, not cases, and a fixture title that happened to begin
 * with `MU-` would otherwise have landed in the specification table.
 *
 * Line structure is preserved so the remaining line-anchored match still works;
 * only the characters inside the literal go.
 */
export function withoutTemplates(src: string): string {
  let out = '';
  let i = 0;
  const copyTo = (end: number) => { out += src.slice(i, end); i = end; };
  while (i < src.length) {
    const two = src.slice(i, i + 2);
    // A line comment, to the end of the line. Backticks are ordinary prose here
    // -- this file and the test file both quote code in comments -- and reading
    // one as a template opener blanked everything after it.
    if (two === '//') {
      const nl = src.indexOf('\n', i);
      copyTo(nl === -1 ? src.length : nl);
      continue;
    }
    if (two === '/*') {
      const close = src.indexOf('*/', i + 2);
      copyTo(close === -1 ? src.length : close + 2);
      continue;
    }
    const ch = src[i];
    // A quoted string, copied whole. **Test titles live here and they quote code
    // in backticks** -- `a \`from\` that is not in the subject` -- so treating
    // those as template openers rewrote the titles to `a \`    \`` and the
    // comparison failed on its own reader. Measured.
    if (ch === "'" || ch === '"') {
      let k = i + 1;
      while (k < src.length && src[k] !== ch) k += src[k] === '\\' ? 2 : 1;
      copyTo(Math.min(k + 1, src.length));
      continue;
    }
    if (ch !== '`') { out += ch; i += 1; continue; }
    // A template literal: keep the delimiters and the line structure, drop the
    // contents, because the fixture specs are written as template literals
    // holding real `test('...')` lines and those are test data, not cases.
    out += '`';
    i += 1;
    while (i < src.length && src[i] !== '`') {
      if (src[i] === '\\') { i += 2; continue; }
      out += src[i] === '\n' ? '\n' : ' ';
      i += 1;
    }
    if (i < src.length) { out += '`'; i += 1; }
  }
  return out;
}

/**
 * The table body: one row per id, its scenarios joined, **ids in numeric order**.
 *
 * Not first-seen order, which is what the first version of this produced and it
 * scattered the ids — `MU-12` after `MU-1`, `MU-58` in the middle — because the
 * test file groups by subject rather than by number. The hand-written table was
 * numeric, and a reviewer looking a case up needs that; the scenarios within a
 * row stay in file order, which is the order they run in.
 */
export function table(src: string): string {
  const byId = new Map<string, string[]>();
  for (const t of titles(src)) {
    const m = /^(MU-\d+)\s+(.*)$/.exec(t);
    if (!m) continue;
    const list = byId.get(m[1]) ?? [];
    list.push(m[2]);
    byId.set(m[1], list);
  }
  const num = (id: string) => Number(id.slice(3));
  const rows = [...byId.entries()]
    .sort((a, b) => num(a[0]) - num(b[0]))
    .map(([id, ss]) => `| **${id}** | ${ss.join('<br>')} |`);
  return ['| Case | Scenarios, named as the tests are named |', '|---|---|', ...rows].join('\n');
}

export function rendered(spec: string, src: string): string {
  const begin = spec.indexOf(BEGIN);
  const end = spec.indexOf(END);
  if (begin === -1 || end === -1) {
    throw new Error(`the generated block markers are missing from ${SPEC}`);
  }
  return spec.slice(0, begin + BEGIN.length) + '\n' + table(src) + '\n' + spec.slice(end);
}

if (import.meta.main) {
  const spec = readFileSync(SPEC, 'utf8');
  const src = readFileSync(FILE, 'utf8');
  const want = rendered(spec, src);
  if (process.argv.includes('--write')) {
    writeFileSync(SPEC, want);
    console.log('scenario table written');
  } else {
    if (spec === want) {
      console.log('scenario table is up to date');
    } else {
      console.error('the scenario table differs from the test file; run: bun tests/scenario-table.ts --write');
      process.exit(1);
    }
  }
}
